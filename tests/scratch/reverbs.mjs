// LazyReverb lifecycle: built when a user arrives, dropped LINGER s after the tail; sound plays meanwhile
import { launch } from '../mobile/lib.mjs';
const h = await launch('chromium', { exclusive: false });
const errs = []; h.page.on('pageerror', e => errs.push(e.message));
await h.page.goto('http://127.0.0.1:4173/?skipTitle&newgame&freeroam=8', { waitUntil: 'load' });
await h.page.waitForFunction(() => window.__game?.worldReady && __game.state === 'play' && __game.audio?.ready, null, { timeout: 240000 });
await h.page.waitForTimeout(6500);
const state = () => h.page.evaluate(() => { const a = __game.audio, f = fx => fx ? [...fx.reverbs.values()].map(r => (r.node ? 'ON' : 'off') + (r.holds ? `/h${r.holds}` : '')).join(',') : '-'; return `radio[${f(a.radioFx)}] cue[${f(a.cueFx)}] zone[${f(a.zoneFx)}] sfx[${a.sfxHall.node ? 'ON' : 'off'}]  ctx ${a.ctx.state}`; });
const level = () => h.page.evaluate(() => new Promise(res => { const a = __game.audio, an = a.ctx.createAnalyser(); a.master.connect(an); const d = new Float32Array(2048); let m = 0, n = 0; const t = setInterval(() => { an.getFloatTimeDomainData(d); for (const v of d) m = Math.max(m, Math.abs(v)); if (++n > 20) { clearInterval(t); a.master.disconnect(an); res(m.toFixed(3)); } }, 50); }));
console.log('free roam on foot      ', await state());
await h.page.evaluate(() => __game.audio.music('mission_start') || __game.audio.music('title'));
await h.page.waitForTimeout(800);
console.log('cue playing            ', await state(), ' peak', await level());
await h.page.evaluate(() => __game.audio.music('stop'));
await h.page.waitForTimeout(1500);
console.log('cue stopped            ', await state());
await h.page.evaluate(() => { const g = __game; void g.debugCar('infernus'); });
await h.page.waitForTimeout(2500);
await h.page.evaluate(() => { const r = __game.audio.radio; if (r.current < 0) r.next?.(); });
await h.page.waitForTimeout(1500);
console.log('in car, radio          ', await state(), ' peak', await level(), ' station', await h.page.evaluate(() => __game.audio.radio.current));
await h.page.evaluate(() => __game.audio.sfx('explosion', { position: __game.player.position.clone() }));
console.log('explosion              ', await state());
console.log('waiting 36 s for linger...');
await h.page.evaluate(() => { __game.audio.radio.setStation(-1); });
await h.page.waitForTimeout(36000);
console.log('after linger           ', await state());
console.log('errors:', errs.slice(0, 3));
await h.browser.close();
