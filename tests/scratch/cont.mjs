import { chromium } from '../lib/browser.mjs';
const browser = await chromium.launch({ headless: true, args: ['--autoplay-policy=no-user-gesture-required', '--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto('http://127.0.0.1:5174/?skipTitle&newgame&mission=3', { waitUntil: 'load' });
await page.waitForFunction(() => window.__game?.worldReady && __game.missions.active, null, { timeout: 90000 });
await page.evaluate(() => { __game.progress.missionsDone.push('chope'); __game.money = 4321; __game.save(); });
await page.goto('http://127.0.0.1:5174/', { waitUntil: 'load' });
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/press_start.png' });
await page.keyboard.press('Enter');
await page.waitForTimeout(2000);
const btns = await page.evaluate(() => [...document.querySelectorAll('button')].map(b => b.textContent.trim()).slice(0, 8));
console.log('title buttons', btns);
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => /continue/i.test(b.textContent)).click());
await page.waitForFunction(() => window.__game?.state === 'play', null, { timeout: 90000 });
await page.waitForTimeout(3000);
console.log(await page.evaluate(() => JSON.stringify({ money: __game.money, done: __game.progress.missionsDone, giver: __game.missions.giver?.mission.id, active: __game.missions.active?.mission.id })));
await page.screenshot({ path: '/tmp/continue.png' });
console.log('errors', errs);
await browser.close();
