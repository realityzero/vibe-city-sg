export const DISTRICTS = RAW.map(([name, ring]) => ({ name, poly: ring.map(P) }));

function inside(x, z, poly) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, zi] = poly[i], [xj, zj] = poly[j];
    if ((zi > z) !== (zj > z) && x < (xj - xi) * (z - zi) / (zj - zi) + xi) c = !c;
  }
  return c;
}
/** @returns {string|null} district name at world (x, z) */
export function districtAt(x, z) {
  for (const d of DISTRICTS) if (inside(x, z, d.poly)) return d.name;
  return null;
}
/** Label anchor per unique district name (area-weighted centroid of its largest polygon). */
export const DISTRICT_LABELS = (() => {
  const best = new Map();
  for (const d of DISTRICTS) {
    let a = 0, cx = 0, cz = 0;
    for (let i = 0, n = d.poly.length; i < n; i++) {
      const [x0, z0] = d.poly[i], [x1, z1] = d.poly[(i + 1) % n];
      const f = x0 * z1 - x1 * z0; a += f; cx += (x0 + x1) * f; cz += (z0 + z1) * f;
    }
    a /= 2; const area = Math.abs(a);
    if (!best.has(d.name) || best.get(d.name).area < area) best.set(d.name, { name: d.name, x: cx / (6 * a), z: cz / (6 * a), area });
  }
  return [...best.values()];
})();

